import { readFile, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

// The published snapshot can lag the deployed backend. Keep this overlay until
// the web documentation publishes the contract introduced in backend PR #103.
const spec = JSON.parse(await readFile(new URL('../openapi/openapi.json', import.meta.url), 'utf8'));
const { Product, BillInquiry, Transaction } = spec.components.schemas;
for (const suffix of ['', '_30d', '_90d']) {
  const removed = ['success_count' + suffix, 'failed_count' + suffix];
  for (const key of removed) delete Product.properties[key];
  Product.required = Product.required.filter((key) => !removed.includes(key));
  const tier = 'sample_size' + suffix;
  Product.properties[tier] = { anyOf: [{ type: 'string', enum: ['rendah', 'sedang', 'tinggi'] }, { type: 'null' }], description: 'Jumlah transaksi final: rendah <50, sedang 50–499, tinggi >=500; null jika belum dihitung.' };
  if (!Product.required.includes(tier)) Product.required.push(tier);
}
const numeric = { anyOf: [{ type: 'number' }, { type: 'string', pattern: '^\\d+$' }] };
BillInquiry.properties.details = {
  description: 'Rincian tagihan yang tersedia; setiap field bersifat opsional.',
  anyOf: [{ type: 'object', properties: {
    lembar_tagihan: { type: 'integer', minimum: 0 }, tarif: { type: 'string' }, daya: numeric, jumlah_peserta: numeric,
    detail: { type: 'array', items: { type: 'object', properties: {
      periode: numeric, nilai_tagihan: numeric, admin: numeric, denda: numeric, biaya_lain: numeric, meter_awal: numeric, meter_akhir: numeric,
    } } },
  } }, { type: 'null' }],
};
Transaction.properties.message.description = 'Teks tampilan tetap; tentukan hasil transaksi berdasarkan status, bukan teks message.';
const types = '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n' + astToString(await openapiTS(spec));
await writeFile(new URL('../src/api-types.ts', import.meta.url), types);
